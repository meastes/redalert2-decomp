#!/usr/bin/env python3
"""Behaviour bodies for the keyboard commands' name slots (native/link/behaviour_commands.cpp).

The 56 CommandClass subclasses (src/shared/command.hpp, Init.cpp) are mostly
unrecovered: their slot functions are leaf/request scaffolds. Natively a class
without its key function (Get_Name, the first declared virtual) has no vtable,
so Init_Commands builds objects whose vtables are zero placeholders and the
first virtual call (Load_Keyboard_Hotkeys: Get_Name) faults.

This tool writes, for every subclass slot that no accepted source defines:

  * Get_Name: the row's leaf returns the address of the stored command name
    (`return 0x7dc998;`); the native body returns that string read from the
    user's game.exe at run time (ra2port::original_data_pointer; AGENTS.md
    "Native phase", user decision 2026-11-08).
  * Get_UI_Name, Get_Category, Get_Description: the row's request scaffold is
    StringTable::Load_String(label, 0, file, line) (0x006F9EC0, the same call
    the accepted TauntCommandClass::Get_UI_Name makes); label and file are the
    addresses the catalog binds to the scaffold's receiver/argument (stored
    strings, read at run time), the line is the scaffold's constant.

Other slots (Execute, the key filters) are left undefined: the link closure
traps them until they are recovered or behaviour-written. Addresses and line
numbers only; no original bytes.

    python3 native/tools/command_rewrites.py      (writes native/link/behaviour_commands.cpp)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/original_target'))
import catalog_io  # noqa: E402

OUT = ROOT / 'native/link/behaviour_commands.cpp'
LOAD_STRING = 0x006F9EC0
NAME_SLOTS = ('Get_Name', 'Get_UI_Name', 'Get_Category', 'Get_Description')


def main():
    header = (ROOT / 'src/shared/command.hpp').read_text()
    classes = []
    number = {}
    for m in re.finditer(r'^class (\w+) : public CommandClass \{(.*?)^\};', header, re.M | re.S):
        slots = re.findall(r'virtual [\w\s\*]+?\b(\w+)\([^)]*\) const;\s*// 0x([0-9A-Fa-f]{8})', m.group(2))
        classes.append((m.group(1), [(n, int(a, 16)) for n, a in slots]))
        field = re.search(r'^\s*int (\w+);\s*// \+0x04', m.group(2), re.M)
        if field:
            number[m.group(1)] = field.group(1)
    sources = {}
    defined = set()
    for f in (ROOT / 'src/recovered').rglob('*.cpp'):
        text = f.read_text(errors='replace')
        if re.fullmatch(r'[0-9a-f]{8}', f.stem):
            sources[int(f.stem, 16)] = text
        for d in re.findall(r'^[^\s/#][^;{]*?\b(\w+CommandClass::\w+)\(', text, re.M):
            defined.add(d)
    catalog = catalog_io.load(catalog_io.locate(ROOT), references=True)
    refs = {}
    for table in catalog['population_references'].values():
        refs.update(table)
    out = ['// generated by native/tools/command_rewrites.py: behaviour bodies of the keyboard',
           '// commands\' name slots (Init.cpp; src/shared/command.hpp). NOT EXACT: every row stays',
           '// unrecovered in the exact tree. Get_Name returns the command name the original stores',
           '// (read from the user\'s game.exe at run time); the text slots call',
           '// StringTable::Load_String with the stored label as the row\'s request scaffold does.',
           '// Slots left out here (Execute, key filters) are trapped by the link closure.',
           '#include "shared/command.hpp"',
           '',
           'namespace ra2port { void *original_data_pointer(unsigned int va); }',
           'extern "C" int ra2_sprintf(char *dst, char const *format, ...);   // port CRT (VC6 sprintf)',
           '',
           'namespace {',
           'char const *Stored(unsigned int va) { return (char const *)ra2port::original_data_pointer(va); }',
           '}',
           '',
           '// 0x0051AF90 CommandClass::Get_UI_Name: the row\'s seed jumps through vtable +0x10',
           '// (slot 4, Get_Description).',
           'wchar_t const *CommandClass::Get_UI_Name() const { return Get_Description(); }',
           '']
    rows = []
    for cls, slots in classes:
        body = []
        for name, addr in slots:
            if name not in NAME_SLOTS or '%s::%s' % (cls, name) in defined:
                continue
            src = sources.get(addr, '')
            if name == 'Get_Name':
                m = re.search(r'\breturn 0x([0-9a-fA-F]+);', src)
                f = re.search(r'FUN_007820f4\(\(int\)\(&DAT_00a4149c\), \(int\)\(s_\w+_([0-9a-f]{8})\), '
                              r'\(int\)\(\*\(undefined4 \*\)\(param_1 \+ 4\)\)\);', src)
                if m and 'Leaf_' in src:
                    body.append('char const *%s::Get_Name() const { return Stored(0x%08Xu); }   // 0x%08X'
                                % (cls, int(m.group(1), 16), addr))
                elif f and number.get(cls):
                    # sprintf(name buffer 0x00A4149C, stored format, the +0x04 number)
                    body.append('char const *%s::Get_Name() const { ra2_sprintf(unknown_command_name_a4149c, '
                                'Stored(0x%08Xu), %s); return unknown_command_name_a4149c; }   // 0x%08X'
                                % (cls, int(f.group(1), 16), number[cls], addr))
                else:
                    continue
            else:
                m = re.search(r'request_%x\(\(unsigned int\)receiver_%x, 0, \(unsigned int\)argument_%x, 0x([0-9a-f]+)u\)'
                              % (addr, addr, addr), src)
                target = refs.get('@request_%x@16' % addr)
                label = refs.get('_receiver_%x' % addr)
                file = refs.get('_argument_%x' % addr)
                if not m or target != LOAD_STRING or label is None or file is None:
                    continue
                body.append('wchar_t const *%s::%s() const { return StringTable::Load_String(Stored(0x%08Xu), 0, '
                            'Stored(0x%08Xu), %d); }   // 0x%08X' % (cls, name, label, file, int(m.group(1), 16), addr))
            rows.append((addr, '%s::%s' % (cls, name)))
        if body:
            out.append('// %s' % cls)
            out += body
            out.append('')
    OUT.write_text('\n'.join(out))
    print('command rewrites: %d slot bodies in %d classes -> %s' % (len(rows), len(classes), OUT.relative_to(ROOT)))
    for addr, name in rows:
        print('0x%08X\t%s' % (addr, name))


if __name__ == '__main__':
    main()
