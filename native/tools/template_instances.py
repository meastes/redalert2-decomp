#!/usr/bin/env python3
"""Instantiate the recovered vector templates the native link still misses.

VC6 emitted a template member wherever a unit used it; the accepted sources
define each instantiation's members in the unit that owns its address (guarded
VECTOR_IMPLEMENT_* includes). Natively, members of instantiations whose owner
unit is not in the tree yet stay undefined. This tool reads the link queue
(gen/link_closure.json), collects the VectorClass<T> / DynamicVectorClass<T>
argument types it names, and writes native/link/template_instances.cpp: an
explicit whole-class instantiation per type, from the recovered template
bodies (shared/vector_class.hpp with VECTOR_IMPLEMENT_ALL). Only element types
that need no definition are taken (builtins, pointers to forward-declared
classes); each candidate is compiled alone first and kept only if it builds.
Explicit instantiations are weak definitions: an owner unit's definition wins.

    python3 native/tools/template_instances.py --build build/native [-j6]
"""
import argparse
import concurrent.futures
import json
import re
import shlex
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEMPLATES = ('VectorClass', 'DynamicVectorClass')
BUILTIN = {'int', 'unsigned int', 'short', 'unsigned short', 'char', 'unsigned char', 'signed char',
           'long', 'unsigned long', 'bool', 'float', 'double', 'long long', 'unsigned long long'}
BUILTIN_WORDS = {'const', 'unsigned', 'signed', 'int', 'char', 'short', 'long', 'bool', 'float', 'double', 'void'}
POINTER = re.compile(r'^((?:const\s+)?)([A-Za-z_]\w*(?:::[A-Za-z_]\w*)*)((?:\s*const)?)\s*\*$')


def element_types(names):
    found = set()
    for name in names:
        m = re.match(r'^(%s)<' % '|'.join(TEMPLATES), name)
        if not m or '(' not in name:
            continue
        depth, i = 1, m.end()
        while i < len(name) and depth:
            depth += {'<': 1, '>': -1}.get(name[i], 0)
            i += 1
        if name[i:i + 2] == '::':
            found.add((m.group(1), name[m.end():i - 1].strip()))
    return found


HEADERS = {}


def defining_headers(overlay):
    """{type name: shared header defining it} over the port-rewritten headers."""
    index = {}
    for h in sorted(overlay.glob('*.hpp')):
        for m in re.finditer(r'^\s*(?:template\s*<[^>]*>\s*)?(?:class|struct)\s+([A-Za-z_]\w*)\s*(?::[^;{]*)?\{',
                             h.read_text(errors='replace'), re.M):
            index.setdefault(m.group(1), 'shared/' + h.name)
        for m in re.finditer(r'^\s*(?:enum|namespace)\s+([A-Za-z_]\w*)\s*(?::\s*\w+\s*)?\{',
                             h.read_text(errors='replace'), re.M):
            index.setdefault(m.group(1), 'shared/' + h.name)
    return index


def spell(t):
    """(declarations / includes, C++ spelling) of an element type, or None."""
    t = ' '.join(t.split())
    if set(re.findall(r'[A-Za-z_]\w*', t)) <= BUILTIN_WORDS:
        return '', t
    names = [n for n in re.findall(r'[A-Za-z_]\w*', t.split('::')[0] if '<' not in t else t)
             if n not in ('const', 'unsigned', 'signed', 'int', 'char', 'short', 'long', 'bool', 'float',
                          'double', 'void')]
    if names and (not POINTER.match(t) or '::' in t or '<' in t):
        includes = []
        for n in names:
            if n in HEADERS:
                includes.append('#include "%s"\n' % HEADERS[n])
            elif n[0].isupper() or '_' in n:
                if n not in HEADERS and not any(n in x for x in includes):
                    return None
        return ''.join(dict.fromkeys(includes)), t
    if t in BUILTIN:
        return '', t
    m = POINTER.match(t)
    if not m:
        return None
    name = m.group(2)
    if name in BUILTIN or name == 'void':
        return '', t
    if '::' in name:
        return None
    return 'class %s;\n' % name, t


def unit_text(items):
    decls = ''.join(sorted({d for d, _, _ in items}))
    body = ''.join('template class %s<%s>;  // instance: %s<%s>::\n' % (tmpl, t, tmpl, t) for _, tmpl, t in items)
    return ('// generated by native/tools/template_instances.py: explicit instantiations of the\n'
            '// recovered vector templates for element types the native link still misses\n'
            '// (weak definitions; the unit that owns an instantiation wins when present).\n'
            '#define VECTOR_IMPLEMENT_ALL\n#include "shared/vector_class.hpp"\n' + decls + body)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--build', type=Path, required=True)
    ap.add_argument('-j', type=int, default=6)
    ap.add_argument('--out', type=Path, default=ROOT / 'native/link/template_instances.cpp')
    ap.add_argument('--extra-names', type=Path, help='more demangled undefined names (one per line)')
    args = ap.parse_args()
    build = args.build.resolve()
    HEADERS.update(defining_headers(build / 'gen/overlay/shared'))
    closure = json.loads((build / 'gen/link_closure.json').read_text())['symbols']
    cc = json.loads((build / 'compile_commands.json').read_text())
    model = next(e for e in cc if '/gen/units/' in e['file'])
    base = shlex.split(model['command'])
    keep_args, skip = [], False
    for a in base:
        if skip:
            skip = False
            continue
        if a in ('-o', '-MF', '-MT'):
            skip = True
            continue
        if a in ('-c', '-MD') or a == model['file']:
            continue
        keep_args.append(a)
    items, refused = [], []
    names = [r['name'] for r in closure if r['cls'] == 'cxx-function']
    if args.extra_names:
        names += args.extra_names.read_text().split('\n')
    previous = sorted(args.out.parent.glob(args.out.stem + '*.cpp'))
    for path in previous:   # instantiations written before stay wanted (their names are defined now)
        names += [m + '(' for m in re.findall(r'// instance: (.+::)$', path.read_text(), re.M)]
    for tmpl, t in sorted(element_types(names)):
        s = spell(t)
        if s is None:
            refused.append('%s<%s>: element type needs its definition' % (tmpl, t))
        else:
            items.append((s[0], tmpl, s[1]))
    tmp = Path(tempfile.mkdtemp(prefix='ra2-tmpl-'))

    def check(k):
        src = tmp / ('t%04d.cpp' % k)
        src.write_text(unit_text([items[k]]))
        proc = subprocess.run(keep_args + ['-fsyntax-only', str(src)], cwd=model['directory'],
                              capture_output=True, text=True)
        return proc.returncode == 0
    with concurrent.futures.ThreadPoolExecutor(args.j) as pool:
        ok = list(pool.map(check, range(len(items))))
    good = [it for it, k in zip(items, ok) if k]
    refused += ['%s<%s>: does not compile alone' % (it[1], it[2]) for it, k in zip(items, ok) if not k]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    for path in previous:
        path.unlink()
    plain = [it for it in good if not it[0].startswith('#include')]
    args.out.write_text(unit_text(plain) + ''.join('// not instantiated: %s\n' % r for r in sorted(refused)))
    # Element types that need their class headers: one unit each (headers that
    # compile alone may not compile together).
    for k, it in enumerate(it for it in good if it[0].startswith('#include')):
        args.out.with_name('%s_%02d.cpp' % (args.out.stem, k)).write_text(unit_text([it]))
    print('template instances: %d written, %d refused (%s)' % (len(good), len(refused), args.out))


if __name__ == '__main__':
    main()
