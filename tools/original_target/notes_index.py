#!/usr/bin/env python3
"""Short index of docs/VC6_MATCHING_NOTES.md for lane briefs.

The notes are the project's compiler-mechanism catalog and have grown past 2,000
lines; a lane that reads them whole pays tens of thousands of tokens before any
work. This writes a one-line-per-mechanism index (section heading, line number,
the first clause of each bullet) so a lane reads the index, then only the
sections whose diff class matches its row.

    python3 tools/original_target/notes_index.py                       # stdout
    python3 tools/original_target/notes_index.py --write docs/VC6_MATCHING_INDEX.md
"""
import argparse
import re
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[2]
NOTES = REPOSITORY / 'docs/VC6_MATCHING_NOTES.md'


def first_clause(text, limit):
    text = re.sub(r'\s+', ' ', text).strip()
    # cut at the first sentence end or semicolon after a few words
    m = re.search(r'^(.{25,}?[.;:])(\s|$)', text)
    clause = m.group(1) if m else text
    return clause if len(clause) <= limit else clause[:limit - 1].rstrip() + '…'


def parse():
    """[(title, first_line, last_line, [bullet texts])] for every '## ' section."""
    lines = NOTES.read_text(errors='replace').splitlines()
    sections = []
    bullet = None
    for i, line in enumerate(lines, 1):
        if line.startswith('## '):
            if sections:
                sections[-1][2] = i - 1
            sections.append([line[3:].strip(), i, len(lines), []])
            bullet = None
        elif not sections:
            continue
        elif re.match(r'^- ', line):
            bullet = [line[2:]]
            sections[-1][3].append(bullet)
        elif bullet is not None and line.startswith('  ') and line.strip():
            bullet.append(line.strip())
        elif not line.strip():
            bullet = None
    return [(t, a, b, [' '.join(x) for x in bl]) for t, a, b, bl in sections]


def build(limit, full):
    out = []
    for title, first, last, bullets in parse():
        if full:
            out.append('\n## %s (L%d-%d)' % (title, first, last))
            out += ['  - %s' % first_clause(b, limit) for b in bullets]
        else:
            lead = first_clause(bullets[0], limit) if bullets else ''
            out.append('- L%d-%d %s (%d): %s' % (first, last, title, len(bullets), lead))
    return out


def section(name):
    for title, first, last, bullets in parse():
        if name.lower() in title.lower():
            lines = NOTES.read_text(errors='replace').splitlines()
            return '\n'.join(lines[first - 1:last])
    return 'no section matches %r' % name


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--write', type=Path, help='write the index here instead of stdout')
    ap.add_argument('--limit', type=int, default=110, help='characters per summary clause')
    ap.add_argument('--full', action='store_true', help='one line per bullet instead of one per section')
    ap.add_argument('--section', help='print the whole section whose title contains this text')
    args = ap.parse_args()
    if args.section:
        print(section(args.section))
        return
    body = ['# VC6 matching notes: index',
            '',
            'Generated by tools/original_target/notes_index.py from docs/VC6_MATCHING_NOTES.md; regenerate after editing the notes.',
            'One line per section: L<first>-<last> title (bullet count): first mechanism. Read only the sections whose',
            'diff class matches your row (`notes_index.py --section <title>` prints one), not the whole file.']
    body += build(args.limit, args.full)
    text = '\n'.join(body) + '\n'
    if args.write:
        args.write.write_text(text)
        print('wrote %s: %d lines, %d bytes (notes: %d bytes)' % (args.write, text.count('\n'), len(text), NOTES.stat().st_size))
    else:
        print(text)


if __name__ == '__main__':
    main()
