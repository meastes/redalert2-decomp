// Adopted supporting quotient operation from the same pinned ra2-decomp MPMath source.
#ifndef SEMI_MASK
#define SEMI_MASK ((unsigned short)~0)
#endif
#ifndef MIN
#define MIN(a,b) (((a) < (b)) ? (a) : (b))
#endif

unsigned short __fastcall mp_quo_digit(unsigned short const *dividend)
{
	unsigned int q, q0, q1, q2;

	q1 = (dividend[-2] ^ SEMI_MASK) * (unsigned int) upton_reciph + upton_reciph;
	q2 = (dividend[-1] ^ SEMI_MASK) * (unsigned int) upton_recipl + (1L << 16);
	q0 = (q1 >> 1) + (q2 >> 1) + 1;

	q1 = (dividend[-1] ^ SEMI_MASK) * (unsigned int) upton_reciph;
	q2 = (dividend[0] ^ SEMI_MASK) * (unsigned int) upton_recipl;
	q = (q0 >> 16) + (q1 >> 1) + (q2 >> 1) + 1;

	q = (q >> (16 - 2)) + (((dividend[0] ^ SEMI_MASK) * (unsigned int) upton_reciph) << 1);
	q >>= upton_mshift;

	return((unsigned short) MIN(q, (unsigned int)(1L << 16) - 1));
}


// Modular exponentiation by repeated squaring (0x005A9860).

int __fastcall XMP_Exponent_Mod(digit *result, digit const *base,
    digit const *exponent, digit const *modulus, int precision)
{
    digit product[MAX_UNIT_PRECISION];
    XMP_Init(result, 1, precision);
    if (XMP_Test_Eq_Int(exponent, 0, precision)) {
        if (XMP_Test_Eq_Int(base, 0, precision)) return -1;
        return 0;
    }
    if (XMP_Test_Eq_Int(modulus, 0, precision)) return -2;
    if (XMP_Compare(base, modulus, precision) >= 0) return -3;
    if (XMP_Compare(exponent, modulus, precision) >= 0) return -4;

    int used = XMP_Significance(modulus, precision);
    if (XMP_Prepare_Modulus(modulus, used)) return -5;
    int bits = XMP_Count_Bits(exponent, used);
    int digits = (bits + 31) / 32;
    if (!digits) return 0;
    digit mask = XMP_Bit_Mask(bits);
    exponent += digits - 1;
    int remaining = bits - 1;
    XMP_Move(result, base, used);
    mask >>= 1;
    if (!mask) {
        mask = UPPER_MOST_BIT;
        --exponent;
    }
    while (remaining--) {
        XMP_Mod_Mult(product, result, result, used);
        if (*exponent & mask) XMP_Mod_Mult(result, product, base, used);
        else XMP_Move(result, product, used);
        mask >>= 1;
        if (!mask) {
            mask = UPPER_MOST_BIT;
            --exponent;
        }
    }
    XMP_Init(product, 0, used);
    XMP_Mod_Mult_Clear(used);
    return 0;
}


// memrev(char *buffer, unsigned int length) (0x005A9BD0)
// Reverses a byte buffer in place (unused).

void __fastcall memrev(char *buffer, unsigned int length)
{
    char *r2 = &(buffer[length - 1]);
    while (buffer < r2) {
        char b = *buffer;
        *buffer++ = *r2;
        *r2-- = b;
    }
}


// pfunc(void const *key, void const *element) (0x005A9BF0)
// Compares two prime-table entries (for the binary search).

int __fastcall pfunc(void const *key, void const *element)
{
    if (*(unsigned short const *)key < *(unsigned short const *)element) {
        return -1;
    }
    return *(unsigned short const *)key > *(unsigned short const *)element;
}


// XMP_Is_Small_Prime(digit const *candidate, int precision) (0x005A9C10)
// Whether the number is in the small-prime table (binary search).

// Binary search of the prime table.
static inline unsigned short const *Search_Primes(unsigned short key)
{
    unsigned short const *base = primeTable;
    int num = sizeof(primeTable) / sizeof(primeTable[0]);
    while (num > 0) {
        int half = num / 2;
        unsigned short const *mid = base + half;
        if (*mid > key) {
            num = half;
        } else if (*mid == key) {
            return mid;
        } else {
            base = mid + 1;
            num = num - half - 1;
        }
    }
    return 0;
}

bool __fastcall XMP_Is_Small_Prime(digit const *candidate, int precision)
{
    if (XMP_Significance(candidate, precision) > 1) {
        return false;
    }

    if (*candidate > primeTable[sizeof(primeTable) / sizeof(primeTable[0]) - 1]) {
        return false;
    }

    return Search_Primes((unsigned short)*candidate) != 0;
}


// XMP_Small_Divisors_Test(digit const *candidate, int precision) (0x005A9C90)
// False if any small prime divides the number.

bool __fastcall XMP_Small_Divisors_Test(digit const *candidate, int precision)
{
    digit quotient[MAX_UNIT_PRECISION];

    for (unsigned short const *ptr = primeTable; ptr < &primeTable[sizeof(primeTable) / sizeof(primeTable[0])]; ptr++) {
        if (XMP_Unsigned_Div_Int(quotient, candidate, *ptr, precision) == 0) {
            return false;
        }
    }
    return true;
}


// XMP_Fermat_Test(digit const *candidate, unsigned rounds, int precision) (0x005A9CE0)
// Fermat test with the first rounds small primes as witnesses.

bool __fastcall XMP_Fermat_Test(digit const *candidate, unsigned rounds, int precision)
{
    digit term[MAX_UNIT_PRECISION];
    XMP_Move(term, candidate, precision);
    XMP_Dec(term, precision);

    for (unsigned i = 0; i < rounds; i++) {
        digit result[MAX_UNIT_PRECISION];
        digit small[MAX_UNIT_PRECISION];
        XMP_Init(small, primeTable[i], precision);
        XMP_Exponent_Mod(result, small, term, candidate, precision);
        if (!XMP_Test_Eq_Int(result, 1, precision)) {
            return false;
        }
    }
    return true;
}


// XMP_Rabin_Miller_Test(Straw &rng, digit const *w, int rounds, int precision) (0x005A9E10)
// Rabin-Miller probable-prime test with rounds random witnesses.

bool __fastcall XMP_Rabin_Miller_Test(Straw &rng, digit const *w, int rounds, int precision)
{
    digit wminus1[MAX_UNIT_PRECISION];
    XMP_Sub_Int(wminus1, w, 1, 0, precision);

    unsigned maxbitprecision = precision * sizeof(digit) * 8;
    unsigned a;
    for (a = 0; a < maxbitprecision; a++) {
        if (XMP_Test_Bit(wminus1, a)) {
            break;
        }
    }

    digit m[MAX_UNIT_PRECISION];
    XMP_Move(m, wminus1, precision);
    XMP_Shift_Right_Bits(wminus1, a, precision);

    for (int i = 0; i < rounds; i++) {
        digit b[MAX_UNIT_PRECISION];
        digit temp[MAX_UNIT_PRECISION];
        XMP_Init(temp, 2, precision);
        XMP_Randomize(b, rng, temp, wminus1, precision);

        digit z[MAX_UNIT_PRECISION];
        XMP_Exponent_Mod(z, b, m, w, precision);

        if (XMP_Test_Eq_Int(z, 1, precision) || XMP_Compare(z, wminus1, precision) == 0) {
            continue;   // passes this round
        }

        unsigned j;
        for (j = 1; j < a; j++) {
            digit t2[MAX_UNIT_PRECISION];
            XMP_Exponent_Mod(t2, z, temp, w, precision);

            if (XMP_Compare(t2, wminus1, precision) == 0) {
                break;  // passed this round
            }
            if (XMP_Test_Eq_Int(z, 1, precision)) {
                return false;
            }
        }
        if (j == a) {
            return false;
        }
    }
    return true;
}


// XMP_Randomize(digit *result, Straw &rng, int nbits, int precision) (0x005AA130)
// A random number of at most nbits bits drawn from rng.

void __fastcall XMP_Randomize(digit *result, Straw &rng, int nbits, int precision)
{
    if (nbits >= precision * (int)sizeof(digit) * 8) {
        nbits = precision * sizeof(digit) * 8;
    }

    unsigned nbytes = nbits / 8 + 1;
    XMP_Init(result, 0, precision);
    rng.Get(result, nbytes);
    ((unsigned char *)result)[nbytes - 1] &= ~((~0) << (nbits % 8));
}


// XMP_Randomize(digit *result, Straw &rng, digit const *minval, digit const *maxval, int precision) (0x005AA1A0)
// A random number in [minval, maxval].

void __fastcall XMP_Randomize(digit *result, Straw &rng, digit const *minval, digit const *maxval, int precision)
{
    digit range[MAX_UNIT_PRECISION];
    XMP_Sub(range, maxval, minval, 0, precision);
    unsigned bit_count = XMP_Count_Bits(range, precision);
    do {
        XMP_Randomize(result, rng, bit_count, precision);
    } while (XMP_Compare(result, range, precision) > 0);

    XMP_Add(result, result, minval, 0, precision);
}


// Primality filter and two Fermat witnesses (0x005AA380).
static inline bool Test_Fermat_Witness_Range(digit const *number,unsigned short const *first,unsigned short const *last,int precision)
{
digit term[MAX_UNIT_PRECISION];
    XMP_Move(term,number,precision);
    XMP_Dec(term,precision);
    for (unsigned short const *witness = first; witness < last; ++witness) {
        digit result[MAX_UNIT_PRECISION];
        digit small[MAX_UNIT_PRECISION];
        XMP_Init(small,*witness,precision);
        XMP_Exponent_Mod(result,small,term,number,precision);
        if (!XMP_Test_Eq_Int(result,1,precision)) return false;
    }
    return true;
}
bool __fastcall XMP_Is_Prime(digit const *number,int precision)
{
    if (!(*number & 1)) return false;
    if (XMP_Is_Small_Prime(number,precision)) return true;
    if (!XMP_Small_Divisors_Test(number,precision)) return false;
    if (!Test_Fermat_Witness_Range(number,primeTable,&primeTable[2],precision)) return false;
    return true;
}
