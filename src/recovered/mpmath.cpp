// XMP_DER_Length_Encode(unsigned long length, unsigned char *output) (0x005A7590)
// Writes a DER length field (short form below 128, else a count byte and
// the big-endian length); returns its size.

// Bytes needed to hold value (at least one).
static inline int Length_Bytes(unsigned long value)
{
    int count = sizeof(value);
    while (count != 0 && !(value >> ((count - 1) * 8))) {
        count--;
    }
    return count;
}

int __fastcall XMP_DER_Length_Encode(unsigned long length, unsigned char *output)
{
    int header_length = 0;

    if (length <= 0x7F) {
        output[0] = (unsigned char)length;
        header_length = 1;
    } else {
        output[0] = (unsigned char)(Length_Bytes(length) | 0x80);
        header_length = 1;
        for (int index = Length_Bytes(length); index != 0; index--) {
            output[header_length++] = (unsigned char)(length >> ((index - 1) * 8));
        }
    }
    return header_length;
}


// XMP_DER_Encode(digit const *from, unsigned char *output, int precision) (0x005A7610)
// Writes the number as a DER INTEGER (tag, length, two's complement
// big-endian bytes); returns the bytes written.

int __fastcall XMP_DER_Encode(digit const *from, unsigned char *output, int precision)
{
    unsigned char buffer[MAX_UNIT_PRECISION * sizeof(digit) + 1];

    int header_length = 0;
    unsigned number_length = XMP_Encode(buffer, from, precision);
    output[header_length++] = 0x02;
    header_length += XMP_DER_Length_Encode(number_length, &output[header_length]);
    memcpy(&output[header_length], buffer, number_length);
    return header_length + number_length;
}


// XMP_DER_Decode(digit *result, unsigned char const *input, int precision) (0x005A76D0)
// Reads a DER INTEGER; malformed or oversized input leaves result unchanged.

void __fastcall XMP_DER_Decode(digit *result, unsigned char const *input, int precision)
{
    if (*input++ == 0x02) {
        unsigned byte_count;

        if ((*input & 0x80) == 0) {
            byte_count = *input++;
        } else {
            int length = *input++ & 0x7F;
            if (length > 2) {
                return;
            }
            byte_count = *input++;
            if (length > 1) {
                byte_count = (byte_count << 8) | *input++;
            }
        }

        if (byte_count <= precision * sizeof(digit)) {
            XMP_Signed_Decode(result, input, byte_count, precision);
        }
    }
}


// XMP_Encode(unsigned char *to, unsigned tobytes, digit const *from, int precision) (0x005A7750)
// Big-endian encoding into exactly tobytes bytes, sign-filled on the left; returns tobytes.

#ifndef MIN
#define MIN(a, b) (((a) < (b)) ? (a) : (b))
#endif

unsigned __fastcall XMP_Encode(unsigned char *to, unsigned tobytes, digit const *from, int precision)
{
    unsigned frombytes = precision * sizeof(digit);
    unsigned char filler = (unsigned char)(XMP_Is_Negative(from, precision) ? 0xff : 0);

    unsigned index;
    for (index = 0; index < (tobytes - frombytes); index++) {
        *to++ = filler;
    }

    unsigned char const *fptr = ((unsigned char const *)from) + MIN(tobytes, frombytes);
    for (index = 0; index < MIN(tobytes, frombytes); index++) {
        *to++ = *--fptr;
    }

    return tobytes;
}


// XMP_Encode(unsigned char *to, digit const *from, int precision) (0x005A77F0)
// Writes the number as minimal two's complement big-endian bytes; returns
// the count. (The scan for the top byte starts precision BYTES into the
// number - original behaviour.)

// Not expanded into XMP_DER_Encode in the original; auto_inline(off)
// reproduces the call (hypothesis: the original was not inlinable there).
#pragma auto_inline(off)
int __fastcall XMP_Encode(unsigned char *to, digit const *from, int precision)
{
    bool is_negative = XMP_Is_Negative(from, precision);
    unsigned char filler = (unsigned char)(is_negative ? 0xFF : 0);

    unsigned char const *number_ptr = (unsigned char const *)from + precision - 1;
    while (number_ptr > (unsigned char const *)from && *number_ptr == filler) {
        number_ptr--;
    }

    int index = 0;
    if (((*number_ptr & 0x80) && !is_negative) || (!(*number_ptr & 0x80) && is_negative)) {
        to[index++] = filler;
    }

    to[index++] = *number_ptr;
    while (number_ptr != (unsigned char const *)from) {
        --number_ptr;
        to[index++] = *number_ptr;
    }
    return index;
}
#pragma auto_inline(on)


// XMP_Signed_Decode(digit *result, unsigned char const *from, int frombytes, int precision) (0x005A7860)
// Reads big-endian two's complement bytes, sign-extending.

void __fastcall XMP_Signed_Decode(digit *result, unsigned char const *from, int frombytes, int precision)
{
    unsigned char fill = (unsigned char)((*from & 0x80) ? 0xFF : 0);
    int fillcount = precision * sizeof(digit) - frombytes;
    unsigned char *dest = (unsigned char *)&result[precision];

    while (fillcount > 0) {
        *--dest = fill;
        fillcount--;
    }
    while (frombytes > 0) {
        *--dest = *from++;
        frombytes--;
    }
}


// XMP_Unsigned_Decode(digit *result, unsigned char const *from, int frombytes, int precision) (0x005A78B0)
// Reads big-endian unsigned bytes, zero-extending.

void __fastcall XMP_Unsigned_Decode(digit *result, unsigned char const *from, int frombytes, int precision)
{
    int fillcount = precision * sizeof(digit) - frombytes;
    unsigned char *dest = (unsigned char *)&result[precision];

    while (fillcount > 0) {
        *--dest = 0;
        fillcount--;
    }
    while (frombytes > 0) {
        *--dest = *from++;
        frombytes--;
    }
}


// XMP_Significance(digit const *number, int precision) (0x005A78F0)
// Number of digits up to the highest non-zero one.

int __fastcall XMP_Significance(digit const *number, int precision)
{
    number += precision - 1;
    while (!*number) {
        if (!--precision) {
            break;
        }
        number--;
    }
    return precision;
}


// XMP_Inc(digit *number, int precision) (0x005A7910)

void __fastcall XMP_Inc(digit *number, int precision)
{
    while (!++(*number)) {
        number++;
        if (!--precision) {
            break;
        }
    }
}


// XMP_Dec(digit *number, int precision) (0x005A7930)

void __fastcall XMP_Dec(digit *number, int precision)
{
    while (--(*number) == (digit)~0UL) {
        number++;
        if (!--precision) {
            break;
        }
    }
}


// XMP_Neg(digit *number, int precision) (0x005A7950)
